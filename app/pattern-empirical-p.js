'use strict';

/**
 * One-sided empirical p-value for a lower-is-better score difference.
 * nullDifferences must come from a valid, pre-specified null/permutation scheme.
 * Plus-one correction prevents a reported p-value of zero.
 */
function empiricalLowerTailP(observedDifference, nullDifferences, options = {}) {
  const minNullSamples = Number.isFinite(options.minNullSamples)
    ? Math.max(1, Math.floor(options.minNullSamples)) : 100;
  if (!Number.isFinite(observedDifference)) throw new TypeError('observedDifference must be finite');
  if (!Array.isArray(nullDifferences) || nullDifferences.length < minNullSamples) {
    throw new TypeError(`nullDifferences must contain at least ${minNullSamples} samples`);
  }
  if (!nullDifferences.every(Number.isFinite)) throw new TypeError('nullDifferences must all be finite');
  const atLeastAsExtreme = nullDifferences.filter(value => value <= observedDifference).length;
  return {
    pValue: (atLeastAsExtreme + 1) / (nullDifferences.length + 1),
    observedDifference,
    nullSamples: nullDifferences.length,
    tail: 'lower',
    correction: 'plus-one',
    note: 'Valid only if null samples were generated by a pre-specified valid procedure; temporal dependence and candidate-selection leakage must be addressed by that procedure.'
  };
}

module.exports = { empiricalLowerTailP };
